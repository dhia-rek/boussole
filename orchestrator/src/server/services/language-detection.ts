export type DetectedLanguage = "fr" | "en";

export function detectLanguage(text: string): DetectedLanguage {
  if (!text || text.trim().length < 20) return "en";

  const words = text
    .toLowerCase()
    .replace(/[^a-zàâäéèêëîïôùûüçœæ\s]/g, " ")
    .split(/\s+/)
    .filter((w) => w.length > 1);

  let frScore = 0;
  let enScore = 0;

  for (const word of words) {
    if (FR_WORDS.has(word)) frScore++;
    if (EN_WORDS.has(word)) enScore++;
  }

  return frScore > enScore ? "fr" : "en";
}

export function languageLabel(lang: DetectedLanguage): string {
  return lang === "fr" ? "French 🇫🇷" : "English 🇬🇧";
}
